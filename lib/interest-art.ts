function blossom(x: number, y: number, radius: number, palette: readonly [number, number, number]): Shape[] {
  const petals = Array.from({ length: 6 }, (_, index): Shape => {
    const angle = index * Math.PI / 3;
    const point = (distance: number, offset = 0) =>
      `${x + Math.cos(angle + offset) * distance} ${y + Math.sin(angle + offset) * distance}`;
    return [
      palette[index % 2],
      x + Math.cos(angle) * radius * 0.68,
      y + Math.sin(angle) * radius * 0.68,
      `M${x} ${y} C${point(radius * 0.86, -0.67)} ${point(radius * 1.19, -0.31)} ${point(radius)} C${point(radius * 1.19, 0.31)} ${point(radius * 0.86, 0.67)} ${x} ${y}Z`,
    ];
  });
  return [...petals, oval(palette[2], x, y, radius * 0.25)];
}

